"""Render Markdown reports for a plain static server; Jekyll builds use the Markdown directly."""
from pathlib import Path
import html
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / '.preview-packages'))
import markdown
import yaml


def build():
    for source in sorted((ROOT / 'trips').glob('*.md')):
        _, front, body = source.read_text(encoding='utf-8').split('---', 2)
        page = yaml.safe_load(front) or {}
        layout = (ROOT / '_layouts' / (page.get('layout', 'trip') + '.html')).read_text(encoding='utf-8')
        # Support the optional-field conditionals shared with the Jekyll layout.
        layout = re.sub(r'{%\s*if page\.(\w+)\s*%}(.*?){%\s*endif\s*%}',
                        lambda match: match[2] if page.get(match[1]) else '',
                        layout, flags=re.DOTALL)
        layout = re.sub(r'{{\s*page\.(\w+)\s*\|\s*escape\s*}}',
                        lambda match: html.escape(str(page.get(match[1]) or ''), quote=True), layout)
        layout = layout.replace("{{ '/index.html' | relative_url }}", '../index.html')
        rendered = markdown.markdown(body, extensions=['extra', 'toc'])
        layout = layout.replace('{{ content }}', rendered)
        if '{{' in layout or '{%' in layout:
            raise ValueError(f'Unsupported template expression in {source}')
        layout = '\n'.join(line.rstrip() for line in layout.splitlines()) + '\n'
        output = source.with_suffix('.html')
        output.write_text('<!-- Generated by scripts/build-trips.py; edit the .md source. -->\n' + layout,
                          encoding='utf-8')
        print(f'Built {output.relative_to(ROOT)}')


if __name__ == '__main__':
    build()

